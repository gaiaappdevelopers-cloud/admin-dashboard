/** True when a key still looks machine-generated (never renamed by the admin). */
export function isAutoGeneratedKey(key: string, prefix: string): boolean {
  return new RegExp(`^${prefix}_[0-9a-z]+_[0-9a-z]+$`).test(key)
}

export function toDynamicFormSections(raw: unknown): DynamicFormSection[] {
  if (!Array.isArray(raw)) return []
  return raw as DynamicFormSection[]
}

/** Recursively collects every invalid section_key/field_key/link key in a set of sections. */
export function collectInvalidKeys(sections: DynamicFormSection[]): string[] {
  const invalid: string[] = []

  function checkKey(key: string) {
    if (!isValidKey(key)) invalid.push(key)
  }

  function checkField(field: DynamicFormField) {
    checkKey(field.field_key)
    if (field.link) {
      checkKey(field.link.destination_key)
      if (field.link.page_key) checkKey(field.link.page_key)
    }
    if (field.complementary_field) checkField(field.complementary_field)
  }

  for (const section of sections) {
    checkKey(section.section_key)
    for (const field of section.fields) checkField(field)
  }

  return invalid
}
