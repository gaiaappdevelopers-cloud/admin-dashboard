let idCounter = 0

function uid(prefix: string): string {
  idCounter += 1
  return `${prefix}_${Date.now().toString(36)}_${idCounter.toString(36)}`
}

/** Shared with schema_key/page_key validation elsewhere in the admin — keep in sync. */
export const SNAKE_CASE_KEY_PATTERN = /^[a-z][a-z0-9]*(_[a-z0-9]+)*$/

export function isValidKey(value: string): boolean {
  return SNAKE_CASE_KEY_PATTERN.test(value)
}

export function slugify(value: string): string {
  return value
    .trim()
    .toLowerCase()
    .normalize("NFD")
    .replace(/[̀-ͯ]/g, "")
    .replace(/[^a-z0-9]+/g, "_")
    .replace(/^_+|_+$/g, "")
}

